/**
 * Resolves static demo company details and builds preview grouped rounds.
 * @param {string} slugOrId - navigation slug, company ID, or URL identifier
 */
export const getDemoCompanyDetail = (slugOrId = '') => {
  const cleanId = String(slugOrId).trim().toLowerCase();
  
  // 1. Direct match on _navSlug or companyId or _id
  let found = STATIC_DEMO_COMPANIES.find(c => 
    c._navSlug.toLowerCase() === cleanId || 
    c.companyId.toLowerCase() === cleanId ||
    c._id.toLowerCase() === cleanId
  );

  // 2. Check for batch-encoded slug (e.g., 'amazon--2027')
  if (!found && cleanId.includes('--')) {
    const [baseName, batch] = cleanId.split('--');
    found = STATIC_DEMO_COMPANIES.find(c => 
      c.company.toLowerCase().includes(baseName) && String(c.batch) === String(batch)
    );
  }

  // 3. Match on company name slug
  if (!found) {
    found = STATIC_DEMO_COMPANIES.find(c => 
      c.company.toLowerCase().replace(/\s+/g, '-') === cleanId ||
      cleanId.includes(c.company.toLowerCase().replace(/\s+/g, '-'))
    );
  }

  // 4. Default fallback if not matched
  const companyData = found || {
    _id: `demo-${cleanId || 'company'}`,
    companyId: `demo-${cleanId || 'company'}`,
    company: cleanId ? cleanId.replace(/-/g, ' ').toUpperCase() : 'Tech Company',
    name: cleanId ? cleanId.replace(/-/g, ' ').toUpperCase() : 'Tech Company',
    role: 'SOFTWARE DEVELOPMENT ENGINEER',
    batch: '2026',
    ctc: 'Role Based',
    cutoff: 7.5,
    totalExperiences: 12,
    avgRounds: 2,
    industry: 'Technology',
    rounds: [
      {
        roundNumber: 1,
        type: 'Technical Round',
        storiesCount: 8,
        topicsCovered: ['Data Structures & Algorithms', 'Database Queries & SQL', 'Problem Solving']
      },
      {
        roundNumber: 2,
        type: 'Managerial & System Design',
        storiesCount: 4,
        topicsCovered: ['System Design Basics', 'Project Architecture', 'Behavioural Questions']
      }
    ]
  };

  // Build the grouped rounds structure for preview display
  const groupedRounds = {};
  const roundsList = companyData.rounds || [
    {
      roundNumber: 1,
      type: 'Technical',
      storiesCount: companyData.totalExperiences || 1,
      topicsCovered: ['SQL', 'OOPS', 'Core CS Fundamentals']
    }
  ];

  roundsList.forEach((r, roundIdx) => {
    const roundKey = String(r.roundNumber || roundIdx + 1);
    const count = r.storiesCount || 1;
    
    // Create 1-2 representative locked preview cards for this round
    const previewCardsCount = Math.min(2, count);
    const cards = [];

    for (let i = 0; i < previewCardsCount; i++) {
      cards.push({
        _id: `${companyData._id}-r${roundKey}-exp${i + 1}`,
        experienceId: `EXPERIENCE ${String(i + 1).padStart(2, '0')}`,
        roundNumber: Number(roundKey),
        roundType: r.type || 'Technical',
        role: companyData.role,
        companyName: companyData.company,
        upvotes: 0,
        isLocked: true,
        topicsCovered: r.topicsCovered || ['SQL', 'OOPS', 'Problem Solving'],
        totalStoriesInRound: count
      });
    }

    groupedRounds[roundKey] = cards;
  });

  return {
    companyInfo: {
      company: companyData.company,
      role: (companyData.role || 'Software Development Engineer').toUpperCase(),
      batch: String(companyData.batch || '2026'),
      ctc: companyData.ctc || 'Role Based',
      totalExperiences: companyData.totalExperiences || 0,
      avgRounds: companyData.avgRounds || roundsList.length,
      logo: companyData.logo || null
    },
    groupedRounds
  };
};
